// Generate `app/theme.css` from the brand tokens (production plan §3, M0).
//
// `docs/ux/brand/tokens.json` is the single source of the design system
// (decision 2026-11-03, "Brand book replaces VISUAL_DIRECTION"). This script
// turns it into CSS and is the only writer of `app/theme.css`:
//
//   node scripts/build-tokens.mjs           write app/theme.css
//   node scripts/build-tokens.mjs --check   exit 1 if app/theme.css is stale
//
// Output, in order:
//   1. `:root` holds the light value of every brand colour as `--ns-<name>`.
//   2. The dark values apply under `prefers-color-scheme: dark` unless the
//      reader picked light (`data-theme="light"`), and under
//      `data-theme="dark"` whatever the system says.
//   3. `@theme` maps the UI's existing role names (`paper`, `leaf`, `ink`,
//      `rule`, `evidence`, `success`, `warning`, `refusal`, `focus`, ...) onto
//      the brand colours, adds the brand-only roles (`brand`, `anchor`, the
//      four decision outcomes and their `-soft` tints), the three font
//      families, the radii and the overlay shadow. Every utility therefore
//      resolves through `var(--ns-*)` and follows the theme without a rebuild.
//
// The role names stay because about 600 class references use them. Two brand
// names cannot be used as role names: `--color-surface` and `--color-raised`
// were retired by UI-01c and the hygiene gate refuses them in shipped CSS, so
// brand `surface` is the role `leaf` and brand `surface-raised` is
// `leaf-raised`.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(APP, "..", "..", "docs", "ux", "brand", "tokens.json");
const TARGET = join(APP, "app", "theme.css");

/** UI role → brand colour. The roles the components already use. */
const ROLES = {
  paper: "ground",
  leaf: "surface",
  "leaf-raised": "surface-raised",
  ink: "ink",
  "ink-muted": "ink-muted",
  // The brand has one secondary text colour; it passes 4.5:1 on surface.
  "ink-faint": "ink-muted",
  rule: "hairline",
  "rule-strong": "ink-muted",
  evidence: "brand",
  success: "include",
  warning: "unclear",
  refusal: "blocked",
  // Brand book §Accessibility: focus shows a 2px brand ring.
  focus: "brand",
};

/** Brand colours that are also roles under their own name. */
const BRAND_ROLES = [
  "brand",
  "brand-soft",
  "on-brand",
  "anchor",
  "anchor-soft",
  "include",
  "include-soft",
  "unclear",
  "unclear-soft",
  "blocked",
  "blocked-soft",
  "exclude",
  "exclude-soft",
];

const FONTS = { display: "display", interface: "sans", mono: "mono" };

function block(selector, lines, indent = "") {
  return `${indent}${selector} {\n${lines.map((line) => `${indent}  ${line}`).join("\n")}\n${indent}}`;
}

export function render(tokens) {
  const colours = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
  for (const name of [...Object.values(ROLES), ...BRAND_ROLES]) {
    if (!(name in colours)) throw new Error(`tokens.json has no colour named ${JSON.stringify(name)}`);
  }
  const shadow = Object.fromEntries(tokens.shadow.tokens.map((t) => [t.name, t.value]));
  const light = [
    ...Object.entries(colours).map(([name, value]) => `--ns-${name}: ${value.light};`),
    ...Object.entries(shadow).map(([name, value]) => `--ns-${name}: ${value.light};`),
  ];
  const dark = [
    ...Object.entries(colours).map(([name, value]) => `--ns-${name}: ${value.dark};`),
    ...Object.entries(shadow).map(([name, value]) => `--ns-${name}: ${value.dark};`),
  ];

  const theme = [
    ...Object.entries(ROLES).map(([role, name]) => `--color-${role}: var(--ns-${name});`),
    ...BRAND_ROLES.map((name) => `--color-${name}: var(--ns-${name});`),
    ...Object.entries(FONTS).map(([role, family]) => `--font-${role}: ${tokens.type.families[family]};`),
    ...tokens.radius.tokens.map((t) => `--${t.name}: ${t.value};`),
    ...Object.keys(shadow).map((name) => `--${name}: var(--ns-${name});`),
  ];

  return [
    "/*",
    " * GENERATED by scripts/build-tokens.mjs from docs/ux/brand/tokens.json.",
    " * Do not edit: change the tokens and run `npm run tokens`. CI runs",
    " * `npm run tokens:check`, which fails when this file is stale.",
    " */",
    "",
    block(":root", ["color-scheme: light;", ...light]),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(':root:not([data-theme="light"])', ["color-scheme: dark;", ...dark], "  "),
    "}",
    "",
    block(':root[data-theme="dark"]', ["color-scheme: dark;", ...dark]),
    "",
    block("@theme", theme),
    "",
  ].join("\n");
}

function main() {
  const tokens = JSON.parse(readFileSync(SOURCE, "utf8"));
  const css = render(tokens);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(TARGET, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // A missing file is stale.
    }
    if (current !== css) {
      console.error("app/theme.css is stale: run `npm run tokens` and commit the result.");
      process.exit(1);
    }
    console.log("app/theme.css is current.");
    return;
  }
  writeFileSync(TARGET, css, "utf8");
  console.log(`wrote ${TARGET}`);
}

main();

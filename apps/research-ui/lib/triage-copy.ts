export const TRIAGE_COPY: Record<Locale, Record<TriageCopyKey, string>> = { en, fr, ar };

/** One triage string, with its `{holes}` filled. A missing hole is an error, never blank. */
export function tc(locale: Locale, key: TriageCopyKey, values: Readonly<Record<string, string | number>> = {}): string {
  return TRIAGE_COPY[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!(name in values)) throw new Error(`triage copy "${key}" needs {${name}}`);
    return String(values[name]);
  });
}

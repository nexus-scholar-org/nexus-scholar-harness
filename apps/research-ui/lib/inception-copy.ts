export const INCEPTION_COPY: Record<Locale, Record<InceptionCopyKey, string>> = { en: EN, fr: FR, ar: AR };

/** Fill `{name}` placeholders; a missing value is a programming error, not a blank. */
export function fillCopy(template: string, values: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => {
    if (!(k in values)) throw new Error(`inception copy needs {${k}}`);
    return String(values[k]);
  });
}

export function inceptionT(locale: Locale) {
  return (key: InceptionCopyKey, values?: Record<string, string | number>) => fillCopy(INCEPTION_COPY[locale][key], values);
}

/**
 * Where a criterion came from, in the reader's language. The engine's own
 * `source` key decides which sentence; an unknown key shows the engine's
 * English `source_label` unchanged.
 */
export function sourceText(locale: Locale, source: string, paradigm: string, engineLabel: string): string {
  const key = `source.${source}` as InceptionCopyKey;
  if (!(key in EN)) return engineLabel;
  return fillCopy(INCEPTION_COPY[locale][key], { paradigm });
}

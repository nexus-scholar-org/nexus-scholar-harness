export type DiscoveryCopyKey = keyof typeof EN;

/** Filled from the English master until the translations are written (replaced below). */
const FR: Record<DiscoveryCopyKey, string> = { ...EN };
const AR: Record<DiscoveryCopyKey, string> = { ...EN };

export const DISCOVERY_COPY: Record<Locale, Record<DiscoveryCopyKey, string>> = { en: EN, fr: FR, ar: AR };

function fillCopy(text: string, values?: Record<string, string | number>): string {
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (match, k: string) => (k in values ? String(values[k]) : match));
}

export function discoveryT(locale: Locale) {
  return (key: DiscoveryCopyKey, values?: Record<string, string | number>) => fillCopy(DISCOVERY_COPY[locale][key], values);
}

/** Database display names: product names, never translated; an unknown name is shown as sent. */
const PROVIDER_NAMES: Record<string, string> = {
  openalex: "OpenAlex",
  semanticscholar: "Semantic Scholar",
  crossref: "Crossref",
  arxiv: "arXiv",
  pubmed: "PubMed",
  biorxiv: "bioRxiv",
};

export function providerName(name: string): string {
  return PROVIDER_NAMES[name] ?? name;
}

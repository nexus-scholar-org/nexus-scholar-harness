export const DISCOVERY_COPY: Record<Locale, Record<DiscoveryCopyKey, string>> = { en: EN, fr: FR, ar: AR };

function fillCopy(text: string, values?: Record<string, string | number>): string {
  if (!values) return text;
  return text.replace(/\{(\w+)\}/g, (match, k: string) => (k in values ? String(values[k]) : match));
}

export function discoveryT(locale: Locale) {
  return (key: DiscoveryCopyKey, values?: Record<string, string | number>) => fillCopy(DISCOVERY_COPY[locale][key], values);
}

/** A counted message: the plural table's form for `count` when it has one (lib/plural.ts), else the catalog's string. */
export function discoveryCountT(locale: Locale) {
  return (key: DiscoveryCopyKey, count: number, values?: Record<string, string | number>) =>
    fillCopy(pluralTemplate(locale, key, count, DISCOVERY_COPY[locale][key]), values);
}

/** Database display names: product names, never translated; an unknown name is shown as sent. */
const PROVIDER_NAMES: Record<string, string> = {
  openalex: "OpenAlex",
  semanticscholar: "Semantic Scholar",
  crossref: "Crossref",
  arxiv: "arXiv",
  pubmed: "PubMed",
  biorxiv: "bioRxiv",
};

export function providerName(name: string): string {
  return PROVIDER_NAMES[name] ?? name;
}

/** M3f: the word for a harvest's preparation state in "not prepared ({state})"; an unknown state is printed as sent. */
export function harvestStateWord(locale: Locale, state: string): string {
  const key = `combined.state.${state}`;
  return key in DISCOVERY_COPY[locale] ? DISCOVERY_COPY[locale][key as DiscoveryCopyKey] : state;
}

export type AdoptionCopyKey = keyof (typeof COPY)["en"];
export const ADOPTION_COPY: Record<Locale, Record<AdoptionCopyKey, string>> = COPY;

export function adoptionText(locale: Locale, key: AdoptionCopyKey, values: Record<string, string | number> = {}): string {
  return ADOPTION_COPY[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => {
    if (!(k in values)) throw new Error(`adoption copy needs {${k}}`);
    return String(values[k]);
  });
}

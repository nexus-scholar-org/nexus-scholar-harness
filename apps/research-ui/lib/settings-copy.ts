/** A string with its `{name}` parameters filled; an unknown parameter stays as written. */
export function settingsT(locale: Locale, key: SettingsCopyKey, values: Record<string, string | number> = {}): string {
  const template = SETTINGS_COPY[locale][key] ?? SETTINGS_COPY.en[key];
  return template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}


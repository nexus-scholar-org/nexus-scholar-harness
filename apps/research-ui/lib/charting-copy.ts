export const CHARTING_COPY: Record<Locale, Record<ChartingCopyKey, string>> = { en: EN, fr: FR, ar: AR };

/** Every refusal code the charting routes can answer, each with its own words (spec 01 "Refusal codes"). */
export const CHARTING_REFUSAL_CODES = [
  "SCREENING_NOT_PUBLISHED", "RECORD_NOT_KEPT", "FULLTEXT_REASON_REQUIRED", "FULLTEXT_REASON_INVALID",
  "CHARTING_VALUE_INVALID", "CHARTING_COLUMN_UNKNOWN", "CHARTING_AMENDMENT_REASON_REQUIRED", "ATTACHMENT_NOT_PDF",
  "ATTACHMENT_TOO_LARGE", "ATTACHMENT_MISSING", "LINK_INVALID", "CHARTING_EXPORT_FORMAT_INVALID",
  "CHARTING_PROTOCOL_REPLACED", "GENERATION_STALE", "BODY_INVALID", "IDEMPOTENCY_CONFLICT", "ATOMIC_COMMIT_FAILED",
  "CHARTING_FORM_STALE",
] as const;

/** One charting string with its `{holes}` filled; a missing hole is an error, never blank. */
export function cc(locale: Locale, key: ChartingCopyKey, values: Readonly<Record<string, string | number>> = {}): string {
  return CHARTING_COPY[locale][key].replace(/\{(\w+)\}/g, (_, name: string) => {
    if (!(name in values)) throw new Error(`charting copy "${key}" needs {${name}}`);
    return String(values[name]);
  });
}

/** The words of a refusal code; a code this page does not know reads as a general refusal (its code is in Details). */
export function refusalWords(locale: Locale, code: string): string {
  const key = `charting.refusal.${code}` as ChartingCopyKey;
  return key in EN ? CHARTING_COPY[locale][key] : CHARTING_COPY[locale]["charting.refusal.unknown"];
}

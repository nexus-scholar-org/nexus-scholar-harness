# -*- coding: utf-8 -*-
"""
SCR1 T4 verification-sample audit (wave-close).
Compares landed T4 third-rater decisions against the closed mutual-EXCLUDE pair lane.

Semantics (standing rule):
- A T4 suggestion does NOT overturn a closed mutual-EXCLUDE.
- T4 EXCLUDE            -> agreement (exclusion-side consistency evidence).
- T4 INCLUDE / PENDING  -> exception record, routed to the human adjudication sheet.
- Zero-INCLUDE signer is reported (rate-limit session hygiene check, not a validity gate).

Outputs NEW files only (never overwrites prior-round artifacts):
- calibration_v03/v03_scr1_t4_audit.json
"""

import json
import pathlib
from collections import Counter, defaultdict

DRIVE = pathlib.Path(__file__).resolve().parents[2]
CAL = DRIVE / "uav-crop-weed-v03" / "calibration_v03"
LANE = CAL / "screening_scr1" / "verification_lane"
DEC = LANE / "decisions"
PACKS = LANE / "packs"

CRIT_SHA = "9ae1f97d"
PROMPT_SHA = "0c7f129d"


def main():
    # 1. Load all 25 T4 decision files, strict validation against pack manifests.
    pack_records = {}  # pack_id -> ordered [screening_id]
    t4_decision = {}  # screening_id -> decision row
    t4_pack_of = {}  # screening_id -> pack
    header_issues = []
    for df in sorted(DEC.glob("pack_*_decisions_T4.json")):
        pid = df.name.replace("_decisions_T4.json", "")
        x = json.loads(df.read_text(encoding="utf-8"))
        rows = x["decisions"]
        pack = json.loads((PACKS / f"{pid}.view3.json").read_text(encoding="utf-8"))
        pmap = {r["screening_id"]: r for r in pack["records"]}
        ids = [r["screening_id"] for r in rows]
        if ids != list(pmap.keys()):
            header_issues.append(f"{pid}: ID list/order mismatch vs pack manifest")
        if x.get("screener_id") != "T4":
            header_issues.append(f"{pid}: screener_id != T4")
        if not str(x.get("criteria_sha256", "")).startswith(CRIT_SHA):
            header_issues.append(f"{pid}: criteria SHA missing/wrong")
        if not str(x.get("prompt_template_sha256", "")).startswith(PROMPT_SHA):
            header_issues.append(f"{pid}: prompt SHA missing/wrong")
        canon = all(
            all(
                f in r
                for f in (
                    "screening_id",
                    "decision",
                    "reason",
                    "reason_code",
                    "criterion_refs",
                    "confidence",
                )
            )
            for r in rows
        )
        if not canon:
            header_issues.append(f"{pid}: non-canonical row schema")
        pack_records[pid] = pmap
        for r in rows:
            t4_decision[r["screening_id"]] = r
            t4_pack_of[r["screening_id"]] = pid

    # 2. Reconstruct the closed mutual-EXCLUDE sample: the verification pack view
    #    files ARE the sample (generated by v03_scr1_verify_sample.py, whose
    #    manifest v03_scr1_verify_sample_manifest.json maps pack_id -> n_records).
    manifest_path = CAL / "v03_scr1_verify_sample_manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    manifest_counts = manifest.get("packs", {})
    sample_ids = []
    for pid, pmap in pack_records.items():
        declared = manifest_counts.get(
            pid, manifest_counts.get(pid.replace("pack_", ""))
        )
        if declared is not None and declared != len(pmap):
            header_issues.append(
                f"{pid}: pack record count {len(pmap)} != manifest {declared}"
            )
        sample_ids.extend(pmap.keys())
    sample_ids = list(dict.fromkeys(sample_ids))

    missing = [sid for sid in sample_ids if sid not in t4_decision]
    extra = [sid for sid in t4_decision if sid not in set(sample_ids)]

    # 3. Audit outcomes.
    agree, exceptions = [], []
    reason_codes = Counter()
    conf_by_decision = defaultdict(list)
    for sid in sample_ids:
        if sid not in t4_decision:
            continue
        row = t4_decision[sid]
        dec = row["decision"]
        conf_by_decision[dec].append(row.get("confidence"))
        reason_codes[str(row.get("reason_code", "UNSPECIFIED"))] += 1
        if dec == "EXCLUDE":
            agree.append(sid)
        else:
            exceptions.append(
                {
                    "screening_id": sid,
                    "pack": t4_pack_of.get(sid),
                    "t4_decision": dec,
                    "t4_reason_code": row.get("reason_code"),
                    "t4_confidence": row.get("confidence"),
                    "t4_reason": row.get("reason"),
                    "criterion_refs": row.get("criterion_refs"),
                    "one_line_support": row.get("one_line_support"),
                    "closed_lane": "mutual_EXCLUDE (pair-lane closed)",
                    "routing": "human adjudication sheet (T4 suggestion does NOT overturn closure)",
                }
            )

    out = {
        "audit": "SCR1_T4_verification_sample_wave_close",
        "workspace": "uav-crop-weed-v03",
        "family": "T4",
        "n_packs": len(pack_records),
        "n_sample_records": len(sample_ids),
        "n_t4_decisions": len(t4_decision),
        "coverage_complete": len(sample_ids) == len(t4_decision) and not extra,
        "missing_t4_decisions": missing,
        "extra_t4_decisions": extra,
        "header_issues": header_issues,
        "totals": dict(Counter(r["decision"] for r in t4_decision.values())),
        "t4_exCLUDE_agreement_count": len(agree),
        "exclusion_side_agreement_rate": round(len(agree) / max(1, len(sample_ids)), 4),
        "exceptions_to_human": exceptions,
        "n_exceptions": len(exceptions),
        "reason_code_distribution": dict(reason_codes.most_common()),
        "mean_confidence_by_decision": {
            d: round(sum(v) / len(v), 3) for d, v in conf_by_decision.items() if v
        },
        "zero_include_signer": {
            "any_include": "INCLUDE"
            in Counter(r["decision"] for r in t4_decision.values()),
            "note": "reporting hygiene only; pack composition is the closed exclusion pool",
        },
        "semantics": (
            "T4 suggestions only; EXCLUDE agreement counted as exclusion-side "
            "error-rate evidence; INCLUDE/PENDING routed to human adjudication; "
            "closed mutual-EXCLUDE records are NOT overturned by T4."
        ),
        "salient_conflicts": [
            e for e in exceptions if str(e.get("t4_decision")) == "INCLUDE"
        ],
    }

    outpath = CAL / "v03_scr1_t4_audit.json"
    outpath.write_text(
        json.dumps(out, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )

    print(
        f"T4 WAVE-CLOSE AUDIT: {len(pack_records)} packs, sample={len(sample_ids)}, "
        f"decisions={len(t4_decision)}, coverage_complete={out['coverage_complete']}"
    )
    print(f"totals={out['totals']}")
    print(
        f"exclusion-side agreement rate={out['exclusion_side_agreement_rate']} "
        f"({len(agree)}/{len(sample_ids)})"
    )
    print(
        f"exceptions to human adjudication={out['n_exceptions']} "
        f"(INCLUDE={len(out['salient_conflicts'])})"
    )
    print("header issues:", header_issues if header_issues else "NONE")
    print("top reason codes:", list(reason_codes.most_common(8)))
    print(f"written -> {outpath}")


if __name__ == "__main__":
    main()
